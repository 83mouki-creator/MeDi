const DICTIONARIES: Record<Exclude<SiteLocale, 'fr'>, Record<string, string>> = { en: EN, ar: AR };

export function translate(locale: SiteLocale, text: string, vars?: TranslationVars): string {
  if (locale === 'fr') return interpolate(text, vars);
  const dictionary = DICTIONARIES[locale];
  const entry = dictionary[text];
  return interpolate(entry ?? text, vars);
}

/** Traducteur lié à une langue, pratique à passer aux composants. */
export type SiteTranslator = (text: string, vars?: TranslationVars) => string;

export function siteTranslator(locale: SiteLocale): SiteTranslator {
  return (text, vars) => translate(locale, text, vars);
}

/** Diagnostic : nombre de traductions disponibles par langue. */
export function siteStringCounts() {
  return {
    fr: 'source',
    en: Object.keys(EN).length,
    ar: Object.keys(AR).length,
  } as const;
}

/** Clés françaises présentes dans les dictionnaires (utile aux tests). */
export function siteTranslatedKeys(locale: Exclude<SiteLocale, 'fr'>): string[] {
  return Object.keys(DICTIONARIES[locale]);
}

