export function translate(locale: AdminLocale, text: string, vars?: TranslationVars): string {
  const template = locale === 'ar' ? (AR[text] ?? text) : text;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match,
  );
}

export type AdminTranslator = (text: string, vars?: TranslationVars) => string;

/** Nombre de chaînes arabes disponibles (diagnostic, aucune donnée sensible). */
export function arabicStringCount(): number {
  return Object.keys(AR).length;
}
