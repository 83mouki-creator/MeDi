/**
 * Internationalisation du back-office.
 *
 * Périmètre volontairement limité à `/admin` : la boutique reste en français
 * (clientèle ivoirienne), tandis que le propriétaire peut piloter sa gestion en
 * arabe. Les noms de produits, catégories et marques ne sont pas traduits : ils
 * restent dans leur langue de saisie.
 *
 * Principe : le texte français sert de clé. Une chaîne non traduite s'affiche
 * donc en français au lieu de casser l'interface — la traduction peut être
 * complétée progressivement sans risque.
 */

export type AdminLocale = 'fr' | 'ar';

export const ADMIN_LOCALE_COOKIE = 'medi_admin_locale';
export const ADMIN_LOCALE_MAX_AGE = 60 * 60 * 24 * 365;

export function isAdminLocale(value: unknown): value is AdminLocale {
  return value === 'fr' || value === 'ar';
}

export function adminDir(locale: AdminLocale): 'ltr' | 'rtl' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

export function localeLabel(locale: AdminLocale): string {
  return locale === 'ar' ? 'العربية' : 'Français';
}

